def md_table(rows, head):
    o = ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
    for r in rows:
        o.append('| ' + ' | '.join(str(x) for x in r) + ' |')
    return '\n'.join(o)


