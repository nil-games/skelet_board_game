# -*- coding: utf-8 -*-
"""v0.8: новая механика Рома.
- Пассивной Жажды нет. Ром тратится в «Раздаче рома» (обязательный слот-выбор в части эпизодов), от недосмотра
  (тревожные слоты «вахта у бочек»), в отдельных событиях и на необязательные траты (разведка, полный вперёд).
- Жажда = число по Команде: 1–3 → 1, 4–7 → 2, 8–10 → 3.
- Пополнение только целенаправленное: «Собрать обломки», магазин, порт, ромовые действия. Рыбалка без Рома.
- Ром 0: не поражение, но в конце каждого раунда Ропот +1, разведка и полный вперёд недоступны. Ром 10: потолок.
Вызывается из content.py после narrative.apply: rum.apply(globals())."""

THIRST = [(1, 3, 1), (4, 7, 2), (8, 10, 3)]


def thirst(crew):
    for a, b, v in THIRST:
        if a <= crew <= b:
            return v
    return 0


PICK_OPTIONS = 'Ром +1 (можно несколько раз), Сокровища +1, Корпус +1'


def apply(ns):
    act, fixed = ns['act'], ns['fixed']
    by = {e['id']: e for e in ns['EVENTS']}

    def retier(eid, n, tiers, texts=None, title=None, note=None, skill=None):
        a = by[eid]['cells'][n]
        a['tiers'] = tiers
        if texts:
            a['texts'] = texts
        if title:
            a['title'] = title
        if note is not None:
            a['note'] = note
        if skill:
            a['skill'] = skill
        assert len(a['texts']) == len(a['tiers']), (eid, n)

    # --- случайный Ром+ из не-ромовых действий убран
    retier('S1', 2, [{'H': -1}, {'F': 1}, {'F': 1, 'T': 1}], note='7+: одна чайка роняет кошелёк.',
           texts=['Ядро попало в ваш бушприт. Чайки аплодируют.', 'Залп распугал стаю; толстая чайка записала замечание.',
                  'Картечь выбила у чайки кошелёк, а заодно уважение.'])
    retier('S2', 5, [{}, {'L': 1}, {'L': 1, 'T': 1}],
           texts=['Желания ускользают, как мыло.', 'Поймали маленькое желание: повезёт.', 'Поймали желание и что-то блестящее.'])
    retier('SH1', 3, [{'T': -1, 'M': -1}, {'T': 1}, {'T': 2}],
           texts=['Договор подписан случайно: вы теперь должны торговцу.', 'Договор честный: торговец доплатил за подпись.',
                  'Нашлась лазейка: торговец платит вам проценты.'])
    retier('SH1', 5, [{'F': -1}, {'T': 1}, {'T': 2, 'F': 1}],
           texts=['Торговец вас заметил. Слава пострадала.', 'Торговец отдал кошелёк, лишь бы вы ушли.',
                  'Торговец сбежал, оставив кошелёк и шляпу.'])
    retier('SH1', 6, [{'T': 2, 'F': 1}])
    # --- «Собрать обломки» (по образцу ЗМ): ≤3 — 1 вариант, 4–6 — 2, 7+ — 3
    pick_texts = ['Выловили немного: хватит на одну вещь.', 'Хороший улов обломков.', 'Обломков целая гора.']
    # (в эпизоде-цикле «Водоворот» обломки давали бесконечный фарм вместо штурвала — перенесены на «Кладбище кораблей»)
    retier('ST2', 4, [{'M': -1}, {'T': 1}, {'T': 1, 'H': 1}],
           texts=['Выловили только ругань с соседнего корабля.', 'В воде нашлось кое-что ценное.', 'Выловили ценность и пару досок.'])
    retier('F2', 4, [{'pick': 1}, {'pick': 2}, {'pick': 3}], title='Собрать обломки с мёртвых кораблей', texts=pick_texts,
           note='Выберите столько вариантов, сколько велит исход: ' + PICK_OPTIONS + '.')
    retier('I1', 4, [{'pick': 1}, {'pick': 2}, {'pick': 3}], title='Собрать, что застряло в шерсти (кокосы, бочонки, монеты)',
           texts=['Нашли кокос. Внутри, кажется, ром.', 'В шерсти бочонок и пара монет.', 'Шерсть оказалась складом.'],
           note='Выберите столько вариантов, сколько велит исход: ' + PICK_OPTIONS + '.')

    # --- вахта у бочек (⚠): если никто не взял слот — Ром −2
    retier('ST1', 5, [{'R': -1}, {}, {'R': 1}], title='Вахта у бочек: привязать ром',
           texts=['Одна бочка уплыла: шторм выпил за ваш счёт.', 'Все бочки на месте.', 'Бочки на месте, и ещё одна приплыла сама.'])
    by['ST1']['cells'][5]['alarm'] = 'Ром −2'
    # S1: тревожный слот 4 («Откупиться натурой») оставлен: Ром −1

    # --- «Раздача рома» (обязательная, выбор): S2, I1 — вместо Перекура; ST1 — слот 6 (один раз за эпизод)
    def handout():
        a = fixed('Раздача рома', {'RT': 0, 'M': 1})
        a['mandatory'] = True
        a['choices'] = [
            ('Налить всем', {'RT': 0, 'M': 1}, 'Кружки звенят, кости стучат: команда довольна.'),
            ('Зажать', {'M': -1}, 'Вы прикрыли бочку собой. Команда смотрит на вас пустыми глазницами.'),
            ('Пустить к бочке', {'RT': 2, 'F': 2}, 'Команда ринулась к бочке. Кто открыл кран, тот герой дня (Слава тому, кто выбрал).'),
        ]
        a['texts'] = ['Выберите один вариант (см. ниже).']
        a['note'] = 'Жажда зависит от Команды: 1–3 → 1, 4–7 → 2, 8–10 → 3. Если Рома меньше, чем нужно, выпивают остаток.'
        return a
    # Обязательный слот — ЛИЧНЫЙ, на слоте 1 (проходной эпизод: Штурвала нет) или на слоте 2 (цикл: слот 1 — Штурвал).
    for eid in ('S2', 'I1'):
        by[eid]['cells'].pop(6, None)       # Перекур убран
        by[eid]['cells'][1] = handout()
    h = handout()
    h['note'] += ' В эпизоде-цикле раздача проходит один раз: на новых кругах слот 2 заблокирован (✗).'
    st2 = by['ST2']['cells']
    st2[6] = st2[2]                          # «Найти слабое место воронки» уходит в общий слот 6
    st2[2] = h
    # шторм: обязательный «Крепить такелаж» с 4-го слота на 2-й, «Выстрелить в тучу» на 4-й
    st1 = by['ST1']['cells']
    st1[2], st1[4] = st1[4], st1[2]

    # --- порты: «в порту пьют за свои» — без Ром −1 в конце
    for p in ns['PORTS']:
        if p.get('end'):
            p['end'] = p['end'].replace(' Ром −1.', '').replace('Ром −1.', '').strip() or None

    # --- рыбалка: только рыба (товар на продажу в Магазине), цена — в монетах
    ns['CATCH'][:] = [('ШТИЛЬ', 'Штиль', [('Килька', 1), ('Окунь', 2), ('Тунец', 3)]), ('МЕЛЬ', 'Янтарная мель (особый штиль)', [('Бычок', 1), ('Карась', 2), ('Осётр', 4)]), ('ЗАВОДЬ', 'Звёздная заводь (особый штиль)', [('Плотва', 1), ('Лунарь', 3), ('Звездун', 4)]), ('МАНГРЫ', 'Костяные мангры (особый штиль)', [('Сом', 1), ('Мурена', 2), ('Костряк', 4)])]

    # --- шкала Рома: без поражения на краях
    ns['SHIP']['R'].update(lose_lo=None, lose_hi=None)
    ns['THIRST'] = THIRST
    ns['thirst'] = thirst
