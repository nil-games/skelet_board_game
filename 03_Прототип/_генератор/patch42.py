def edit(path, pairs, regex=False):
    s = open(path, encoding='utf-8').read()
    for a, b in pairs:
        if regex:
            s2 = re.sub(a, b, s)
            if s2 == s:
                print('пропуск rx', os.path.basename(path), a[:50])
            s = s2
        else:
            if a not in s:
                print('пропуск', os.path.basename(path), a[:60])
                continue
            s = s.replace(a, b, 1)
    open(path, 'w', encoding='utf-8').write(s)


