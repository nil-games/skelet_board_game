# -*- coding: utf-8 -*-
"""Переименование навыков: Нюх→Вездесуй, Костяк→Кальций, Хватка→Мормышка, Глазомер→Шмаляние, Жуть→Понты. Навигация («Курс») пока без изменений."""
import re, os, glob

RULES = [
    (r'Нюх(?!-флакон)(а|у|ом|е)?\b', {'': 'Вездесуй', 'а': 'Вездесуя', 'у': 'Вездесую', 'ом': 'Вездесуем', 'е': 'Вездесуе'}),
    (r'Костяк(а|у|ом|е)?\b', {'': 'Кальций', 'а': 'Кальция', 'у': 'Кальцию', 'ом': 'Кальцием', 'е': 'Кальции'}),
    (r'Хватк(а|и|е|у|ой)\b', {'а': 'Мормышка', 'и': 'Мормышки', 'е': 'Мормышке', 'у': 'Мормышку', 'ой': 'Мормышкой'}),
    (r'Глазомер(а|у|ом|е)?\b', {'': 'Шмаляние', 'а': 'Шмаляния', 'у': 'Шмалянию', 'ом': 'Шмалянием', 'е': 'Шмалянии'}),
    (r'Жут(ь|и|ью)\b', {'ь': 'Понты', 'и': 'Понтов', 'ью': 'Понтами'}),
]


def convert(text):
    n = 0
    for pat, mp in RULES:
        def sub(m):
            nonlocal n
            n += 1
            return mp[m.group(1) or '']
        text = re.sub(pat, sub, text)
    return text, n


files = [f for f in glob.glob('*.py') if not f.startswith('patch') and f not in ('sim.py',)]
files += ['../../01_Правила.md', '../../02_Дизайн_буклета.md', '../README.md']
total = 0
for f in files:
    if not os.path.exists(f):
        continue
    t = open(f, encoding='utf-8').read()
    new, n = convert(t)
    if n:
        open(f, 'w', encoding='utf-8').write(new)
        print(f, n)
        total += n
print('замен', total)
