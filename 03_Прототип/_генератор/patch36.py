# -*- coding: utf-8 -*-
"""v0.16: «Диковины» → «Диковинки»; «Подношение» → «Поминки» (как называет автор)."""
import re, os, glob
os.chdir(os.path.dirname(os.path.abspath(__file__)))
BASE = r'F:\Projects\BoardGames\Корабль призрак'
files = [BASE + r'\01_Правила.md', BASE + r'\Каталог_предметов.md', BASE + r'\Правила_написания_событий.md', BASE + r'\03_Прототип\README.md'] + [
    f for f in glob.glob('*.py') if not f.startswith('patch') and f not in ('ctx.py',)]

# --- Диковинки
DIK = [
    ('ДИКОВИНЫ', 'ДИКОВИНКИ'),
    ('Диковин(?![а-яё])', 'Диковинок'), ('диковин(?![а-яё])', 'диковинок'),
    ('Диковины', 'Диковинки'), ('диковины', 'диковинки'),
    ('Диковина', 'Диковинка'), ('диковина', 'диковинка'),
    ('Диковину', 'Диковинку'), ('диковину', 'диковинку'),
    ('Диковине', 'Диковинке'), ('диковине', 'диковинке'),
    ('Диковиной', 'Диковинкой'), ('диковиной', 'диковинкой'),
    ('Диковинам', 'Диковинкам'), ('диковинам', 'диковинкам'),
    ('Диковинами', 'Диковинками'), ('диковинами', 'диковинками'),
    ('Диковинах', 'Диковинках'), ('диковинах', 'диковинках'),
]
# --- Поминки
POM = [
    (r'(?:\(рабочее название, бывшие «Поминки»\)|, бывшие «Поминки»|\(бывшие «Поминки»\)| бывшие «Поминки»)', ''),
    ('в Подношении', 'на Поминках'), ('в подношении', 'на Поминках'),
    ('Подношении', 'Поминках'), ('Подношения', 'Поминок'), ('Подношению', 'Поминкам'), ('Подношением', 'Поминками'),
    ('на Подношение', 'на Поминки'),
    ('Подношение', 'Поминки'), ('подношение', 'поминки'),
]
n = 0
for f in files:
    s = open(f, encoding='utf-8-sig').read()
    o = s
    for a, b in DIK + POM:
        s = re.sub(a, b, s)
    if s != o:
        open(f, 'w', encoding='utf-8').write(s)
        n += 1
        print(os.path.basename(f))
print('файлов', n)
