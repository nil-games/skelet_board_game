# -*- coding: utf-8 -*-
"""v0.11: экономика «скелеты хотят разбогатеть».
- Сокровища без предела. Доход ~5–6 монет на скелета за рейс (симуляция).
- Магазин: покупок за визит сколько угодно (складчина разрешена), товары из столбцов d6 — 1 экз. Снаряжение 4. Диковинки 3–9 с ✦: их сжигают на Поминках
  (Искры = число ✦). Роскоши как отдельного столбца нет: «роскошь» — накопить на дорогую диковинку
  или купить несколько дешёвых за несколько визитов.
- Рыба — только товар: Рыночный порт по цене, Захолустная пристань −1 (мин. 1), Рыбацкая деревня +1, остальные порты не берут.
- Проверка размера Команды: слот открыт, только если Команда ≥ N (crew_req).
- Благословение (плохое: 2 кубика, худший) и Проклятие (хорошее: 2 кубика, лучший) — эффекты 'BL'/'CU'.
Вызывается из content.py последним: economy.apply(globals())."""

CURIO_STARS = {}   # название диковинки -> число ✦


def apply(ns):
    shop = dict(ns['SHOP'])
    # --- снаряжение дороже
    ns['SHOP'][1] = ('СНАРЯЖЕНИЕ', [(n, 4, e) for n, _, e in shop['СНАРЯЖЕНИЕ']])
    # --- диковинки: цена и ✦ для Поминок
    curios = [
        ('Ракушка', 3, 1, 'Приложить к уху: Разведка 2.'),
        ('Шкатулка', 3, 1, 'Открыть: Удача +2.'),
        ('Зуб кита', 4, 1, 'Показать врагу: в бою враг теряет 2 Корпуса.'),
        ('Склянка', 6, 2, 'Выпустить туман: в эпизоде-цикле корабль уходит из клетки на 1 без проверки штурвала.'),
        ('Часы', 7, 2, 'Отмотать: перебросить любую проверку, свою или чужую.'),
        ('Бутыль', 9, 3, 'Джинн-стажёр: исход проверки на ступень выше (не выше «10+»).'),
    ]
    items = []
    for nm, pr, st, ef in curios:
        CURIO_STARS[nm] = st
        items.append((nm, pr, '%s Один раз. Или сжечь на Поминках (%d %s).' % (ef, st, 'Искра' if st == 1 else 'Искры' if st < 5 else 'Искр')))
    ns['SHOP'][2] = ('ДИКОВИНКИ', items)
    ns['CURIOS'][:] = []
    ns['CURIO_INFO'] = {nm: (pr, st, ef) for nm, pr, st, ef in curios}
    offer = '; '.join('%s — %d' % (nm, st) for nm, _, st, _ in curios)
    # --- базовые нужды: Курочка и Ремонт по +1 (можно покупать сколько угодно), Бочка и Большой ремонт — опт
    base = []
    for nm, pr, ef in ns['SHOP'][0][1]:
        if nm == 'Курочка по-карибски':
            pr, ef = 1, 'Провиант: Ром +1 (скелеты не едят, но очень любят нюхать). Покупать можно сколько угодно.'
        elif nm == 'Ремонт судна':
            pr, ef = 1, 'Корпус +1. Покупать можно сколько угодно.'
        elif nm == 'Бочка рома':
            ef = 'Опт: Ром +4 за 3 монеты (штучно было бы 4).'
        elif nm == 'Большой ремонт':
            ef = 'Опт: Корпус +4 за 3 монеты (штучно было бы 4).'
        base.append((nm, pr, ef))
    ns['SHOP'][0] = (ns['SHOP'][0][0], base)
    # --- проклятый товар в услугах: «Клятый пятак» вместо Парикмахера
    svc = [x for x in shop['УСЛУГИ']]
    svc[3] = ('Клятый пятак', 2, 'Проклятие (✓ метка): следующая проверка — 2 кубика, берёте лучший.')
    ns['SHOP'][4] = ('УСЛУГИ', svc)
    ns['CURIO_STARS'] = CURIO_STARS

    # --- Поминки: Искры = ✦ на сжигаемых диковинках
    for p in ns['PORTS']:
        a = p['cells'].get(4)
        if a and a['title'].startswith('Поминки'):
            a['title'] = 'Поминки: 1 Диковинка или 2 Снаряжения → Искры'
            a['note'] = ('Положите на алтарь предков до 2 приношений: 1 Диковинка (Искры: %s) или 2 Снаряжения (1 Искра). '
                         'Рыбу нельзя. Название рабочее .' % offer)
            a['texts'] = ['Вы выложили на алтарь предков дорогие вещицы. Свечи вспыхнули: воспоминание стало ярче.']

    by = {e['id']: e for e in ns['EVENTS']}
    # --- проверка размера Команды: абордаж «Кредита» (SH1, слот 4) открыт при Команде ≥ 5
    a = by['SH1']['cells'][4]
    a['title'] = 'Взять «Кредит» на абордаж'
    a['crew_req'] = 5
    a['tiers'] = [{'C': -1, 'M': 1}, {'T': 2, 'D': 1}, {'T': 3, 'D': 1}]
    a['texts'] = ['Абордаж захлебнулся: одного матроса взяли в залог, команда ворчит.',
                  'Взяли кассу «Кредита».', 'Взяли кассу и сейф с процентами.']
    a['note'] = 'Открыт, только если Команда ≥ 5: маленькой командой на абордаж не ходят.'
    # SH2: маленькую команду Бодрячок «перевоспитывает»
    by['SH2']['end'] = by['SH2']['end'].replace('Опасность +1.', 'Опасность +1. Если Команда < 4: Команда −1 (ещё один ушёл на зарядку).')

    # --- Благословение и Проклятие
    ch = by['SH2']['cells'][6]
    ch['choices'] = [(lab, dict(eff, BL=1) if lab.startswith('Согласиться') else eff, txt + (' Вас благословили бодростью.' if lab.startswith('Согласиться') else ''))
                     for lab, eff, txt in ch['choices']]
    j = by['S2']['cells'][4]          # джинн: провал — благословение
    j['tiers'][0] = dict(j['tiers'][0], BL=1)
    j['texts'][0] += ' И ещё джинн вас благословил. От души.'
    d = by['F2']['cells'][6]          # диковинка духам — проклятие (хорошо)
    d['tiers'][0] = dict(d['tiers'][0], CU=1)
    d['texts'][0] += ' Духи прокляли вас на удачу.'
    e = by['F1']['cells'][3]          # спор с эхом, отличный исход — проклятие
    e['tiers'][-1] = dict(e['tiers'][-1], CU=1)
    e['texts'][-1] += ' Эхо прокляло вас напоследок: повезёт.'
    for hz in ns['HAZARDS']:          # святая вода — благословение всем
        if hz['id'] == 'X2':
            hz['eff']['BL'] = 1
            hz['text'] += ' Каждый скелет получает Благословение.'
    ns['EFFECT_NAMES']['BL'] = 'Благословение'
    ns['EFFECT_NAMES']['CU'] = 'Проклятие'
