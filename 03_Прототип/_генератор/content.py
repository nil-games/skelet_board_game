def fx(d):
    """Эффекты в строку."""
    if not d:
        return '—'
    out = []
    for k, v in d.items():
        if k == 'catch':
            out.append({1: 'Улов: один бросок d6', 2: 'Улов: два броска d6, выберите один', 3: 'Улов: два броска d6, берите оба'}[v])
        elif k == 'mv':
            out.append('Ход %d' % v)
        elif k == 'sc':
            out.append('Разведка %d' % v)
        elif k == 'RT':
            out.append('Ром −Жажда' if v == 0 else 'Ром −(Жажда+%d)' % v)
        elif k in ('BL', 'CU'):
            out.append({'BL': 'Благословение', 'CU': 'Проклятие'}[k])
        elif k == 'pick':
            out.append('Обломки: %d %s' % (v, 'вариант' if v == 1 else 'варианта'))
        else:
            out.append('%s %s%d' % (EFFECT_NAMES[k], '+' if v > 0 else '−', abs(v)))
    return ', '.join(out)


