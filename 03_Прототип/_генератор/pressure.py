# -*- coding: utf-8 -*-
"""v0.10: давление без хардкора (по образцу «Забытых морей»).
- Новый круг эпизода-цикла стоит: Ропот (команда злится, что топчемся) и, в шторме и водовороте, Корпус.
- Команда убывает от событий: часть провалов (≤3) и опасные события теряют матросов.
- Опасность в свободном плавании — фоновая: опасные события есть, поражения на 6 нет (его включает сценарий).
Параметры CFG можно переопределить для симуляции (env PRESS="circle_M,storm_H,crew").
Вызывается из content.py после mood.apply: pressure.apply(globals())."""
import os

CFG = dict(circle_M=1, storm_H=1, crew=1)
if os.environ.get('PRESS'):
    _v = [int(x) for x in os.environ['PRESS'].split(',')]
    CFG = dict(circle_M=_v[0], storm_H=_v[1], crew=_v[2])

# провалы (исход ≤3), на которых теряется матрос: (эпизод, слот, текст-дополнение)
CREW_LOSS = [
    ('S1', 5, 'Одного матроса чайки унесли в гнездо.'),
    ('ST1', 2, 'Одного матроса смыло за борт.'),
    ('ST2', 1, 'Одного матроса затянуло в воронку.'),
    ('SH1', 4, 'Одного матроса оставили у торговца в залог.'),
    ('SH2', 5, 'Один матрос записался на зарядку и ушёл к Бодрячку.'),
    ('F1', 1, 'Один матрос пошёл на голос эха и не вернулся.'),
    ('F2', 5, 'Один матрос остался на вечеринке навсегда.'),
]


def apply(ns):
    by = {e['id']: e for e in ns['EVENTS']}
    # --- цена нового круга
    for e in ns['EVENTS']:
        if e.get('flow') != 'loop':
            continue
        circle = {}
        if CFG['circle_M']:
            circle['M'] = CFG['circle_M']
        if CFG['storm_H'] and e['hint'] == 'st':
            circle['H'] = -CFG['storm_H']
        e['circle'] = circle
        if circle:
            txt = ns['fx'](circle)
            e['end'] = (e.get('end') or '').replace(
                'Если корабль не покинул клетку, следующий раунд читайте этот же эпизод (новый круг).',
                'Если корабль не покинул клетку: %s, и следующий раунд читайте этот же эпизод (новый круг).' % txt)
    # --- потеря команды на провалах и в опасных событиях
    if CFG['crew']:
        for eid, n, add in CREW_LOSS:
            a = by[eid]['cells'][n]
            a['tiers'][0] = dict(a['tiers'][0], C=-CFG['crew'])
            a['texts'][0] = a['texts'][0] + ' ' + add
        for hz in ns['HAZARDS']:
            if 'C' not in hz['eff']:
                hz['eff']['C'] = -1
    # --- Опасность в свободном плавании без поражения (его включает сценарий)
    ns['SHIP']['D']['lose_hi'] = None
    ns['PRESS_CFG'] = CFG
