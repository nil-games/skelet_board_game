def patch(p, pairs, regex=False):
    s = open(p, encoding='utf-8').read()
    for a, b in pairs:
        if regex:
            s, n = re.subn(a, b, s)
            if not n:
                print('пропуск regex', a[:60]); continue
        else:
            if a not in s:
                print('пропуск', os.path.basename(p), a[:60]); continue
            s = s.replace(a, b, 1)
    open(p, 'w', encoding='utf-8').write(s)


