def rep(a, b, rx=False):
    global s
    if rx:
        s2 = re.sub(a, b, s)
        if s2 == s:
            print('пропуск rx', a[:50]); return
        s = s2
        return
    if a not in s:
        print('пропуск', a[:50]); return
    s = s.replace(a, b, 1)


