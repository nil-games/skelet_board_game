# -*- coding: utf-8 -*-
"""Добыча -> Сокровища (мн. число) во всех документах и генераторах."""
import os, glob
base = r'F:\Projects\BoardGames\Корабль призрак'
fs = glob.glob(base + r'\*.md') + [base + r'\03_Прототип\README.md'] + [
    f for f in glob.glob(base + r'\03_Прототип\_генератор\*.py')
    if not os.path.basename(f).startswith('patch') and os.path.basename(f) not in ('ctx.py', 'sim.py')]
SPECIAL = [
    ('сбросить до 2 Добычи, за каждую Искра +1', 'сбросить до 2 Сокровищ, за каждое Искра +1'),
    ('Искра за каждую сброшенную Добычу (макс. 2)', 'Искра за каждое сброшенное Сокровище (макс. 2)'),
    ('ставят 1–2 Добычи', 'ставят 1–2 Сокровища'),
    ('Ставка 1 Добыча на исход', 'Ставка 1 Сокровище на исход'),
    ('Её можно разделить между несколькими ставками', 'Их можно разделить между несколькими ставками'),
    ('всю \'\n              \'Добычу, которую вы принесли', 'все \'\n              \'Сокровища, которые вы принесли'),
    ('Ставки делаются Добычей', 'Ставки делаются Сокровищами'),
    ('Ставки: Добыча. Её', 'Ставки: Сокровища. Их'),
    ('T добыча', 'T сокровища'),
]
GENERIC = [('Добычу', 'Сокровища'), ('Добычей', 'Сокровищами'), ('Добыче', 'Сокровищах'), ('Добычи', 'Сокровищ'), ('Добыча', 'Сокровища'),
           ('добыча,', 'сокровища,')]
tot = 0
for f in fs:
    t = open(f, encoding='utf-8').read()
    o = t
    for a, b in SPECIAL + GENERIC:
        if a in ('добыча,',) and f.endswith('content.py') is False:
            continue
        t = t.replace(a, b)
    if t != o:
        open(f, 'w', encoding='utf-8').write(t)
        print(os.path.basename(f))
        tot += 1
print('файлов', tot)
