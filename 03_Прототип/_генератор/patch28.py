def patch(p, pairs):
    s = open(p, encoding='utf-8').read()
    for a, b in pairs:
        if a not in s:
            raise SystemExit('НЕТ в %s: %s' % (p, a[:90]))
        s = s.replace(a, b)
    open(p, 'w', encoding='utf-8').write(s)


